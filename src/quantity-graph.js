"use strict";

const chart = document.getElementById("chart");
const status = document.getElementById("chart-status");
const timeline = document.getElementById("timeline");
const timelineTrack = document.getElementById("timeline-track");
const valueOutput = document.getElementById("point-value");

let graphData;
let activeRequest;
let scrollTimer;
let earliest;
let latestStart;
let selectedStart;
const DAY = 86400000;
const parseDate = value => new Date(`${value}T00:00:00Z`);
const isoDate = value => value.toISOString().slice(0, 10);
function shiftYears(value, years) {
  const shifted = new Date(value);
  shifted.setUTCFullYear(shifted.getUTCFullYear() + years);
  if (shifted.getUTCMonth() !== value.getUTCMonth()) shifted.setUTCDate(0);
  return shifted; 
}
function layoutTimeline() {
  if (!graphData) return;
  const days = (latestStart - earliest) / DAY;
  timelineTrack.style.width = `${timeline.clientWidth * (1 + days / 730)}px`;
  timeline.scrollLeft = days ? (selectedStart - earliest) / DAY / days * (timeline.scrollWidth - timeline.clientWidth) : 0;
}
const number = new Intl.NumberFormat("en-GB", { maximumFractionDigits: 2 });

async function loadGraph(start, end) {
  activeRequest?.abort();
  chart.setAttribute("aria-busy", "true");
  status.textContent = "Loading quantity data…";
  const controller = new AbortController();
  activeRequest = controller;
  const timeout = setTimeout(() => controller.abort(), 30000);
  try {
    if (location.protocol === "file:") throw new Error("Open this page through the Python backend at http://127.0.0.1:8000/quan_price.html.");
    const params = new URLSearchParams();
    if (start) params.set("start", start);
    if (end) params.set("end", end);
    const response = await fetch(`/api/quantity-graph?${params}`, { signal: controller.signal });
    const contentType = response.headers.get("content-type") || "";
    if (!contentType.includes("application/json")) throw new Error("The quantity API is unavailable. Run the Python backend and open http://127.0.0.1:8000/quan_price.html.");
    const data = await response.json();
    if (activeRequest !== controller) return;
    if (!response.ok) throw new Error(typeof data.detail === "string" ? data.detail : "Unable to load that date range.");
    // SVG is generated by our own Matplotlib endpoint; no user markup is used.
    chart.innerHTML = data.svg;
    chart.querySelector("svg").classList.add("d-block", "w-100", "h-auto");
    graphData = data;
    if (!earliest) {
      earliest = parseDate(data.min);
      latestStart = shiftYears(parseDate(data.max), -2);
      selectedStart = parseDate(data.start);
      document.getElementById("history-start").textContent = data.min.slice(0, 4);
      document.getElementById("history-end").textContent = data.max.slice(0, 4);
      layoutTimeline();
    }
    const rows = document.getElementById("forecast-rows");
    rows.replaceChildren();
    for (const point of data.forecast) {
      const row = document.createElement("tr");
      for (const text of [point.date, number.format(point.quantity)]) {
        const cell = document.createElement("td");
        cell.textContent = text;
        row.appendChild(cell);
      }
      rows.appendChild(row);
    }
    document.getElementById("forecast-summary").textContent = `Weekly forecast values (${data.forecast.length} weeks)`;
    valueOutput.textContent = "Hover over or tap the graph to inspect a weekly value.";
    status.textContent = `Showing ${data.start} to ${data.end}. Forecast begins ${data.forecast_start}.`;
  } catch (error) {
    if (activeRequest !== controller) return;
    status.textContent = (graphData ? "Previous graph retained. " : "") + (error.name === "AbortError"
      ? "Loading timed out. Try again."
      : error instanceof TypeError ? "Cannot reach the backend. Start it with python -m uvicorn backend:app --reload."
      : error.message);
  } finally {
    clearTimeout(timeout);
    if (activeRequest === controller) chart.setAttribute("aria-busy", "false");
  }
}

timeline.addEventListener("scroll", () => {
  if (!graphData) return;
  const extent = timeline.scrollWidth - timeline.clientWidth;
  const dayOffset = extent ? Math.round(timeline.scrollLeft / extent * (latestStart - earliest) / DAY) : 0;
  const nextStart = new Date(earliest.getTime() + dayOffset * DAY);
  if (nextStart.getTime() === selectedStart.getTime()) return;
  selectedStart = nextStart;
  clearTimeout(scrollTimer);
  scrollTimer = setTimeout(() => loadGraph(isoDate(nextStart), isoDate(shiftYears(nextStart, 2))), 120);
});
chart.addEventListener("wheel", event => {
  const delta = event.deltaX || (event.shiftKey ? event.deltaY : 0);
  if (!delta || !graphData) return;
  const before = timeline.scrollLeft;
  timeline.scrollLeft += delta * (event.deltaMode === 1 ? 16 : event.deltaMode === 2 ? timeline.clientWidth : 1);
  if (timeline.scrollLeft !== before) event.preventDefault();
}, { passive: false });
new ResizeObserver(layoutTimeline).observe(timeline);

function inspectPoint(event) {
  const svg = chart.querySelector("svg");
  if (!svg || !graphData) return;
  const position = svg.createSVGPoint();
  position.x = event.clientX;
  position.y = event.clientY;
  const local = position.matrixTransform(svg.getScreenCTM().inverse());
  const closest = graphData.points.reduce((best, point) =>
    Math.abs(point.x - local.x) < Math.abs(best.x - local.x) ? point : best);
  valueOutput.textContent = `${closest.kind} · Week starting ${closest.date} · ${number.format(closest.quantity)} tonnes`;
  let marker = svg.querySelector("#hover-marker");
  if (!marker) {
    marker = document.createElementNS("http://www.w3.org/2000/svg", "circle");
    marker.id = "hover-marker";
    marker.setAttribute("r", "4");
    marker.setAttribute("fill", "#fff");
    marker.setAttribute("stroke-width", "2");
    marker.setAttribute("pointer-events", "none");
    svg.appendChild(marker);
  }
  marker.setAttribute("cx", closest.x);
  marker.setAttribute("cy", closest.y);
  marker.setAttribute("stroke", closest.kind === "Forecast" ? "#b85a0d" : "#2463a6");
}
chart.addEventListener("pointermove", inspectPoint);
chart.addEventListener("click", inspectPoint);
chart.addEventListener("pointerleave", () => chart.querySelector("#hover-marker")?.remove());
loadGraph();
